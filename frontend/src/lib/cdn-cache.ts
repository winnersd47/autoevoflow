// Заголовки кэширования на CDN Vercel.
//
// Зачем: в ноябре 2026 команда на тарифе Hobby исчерпала лимит «Fast Origin Transfer» (11,77 ГБ из 10 ГБ) —
// это трафик из серверных функций в CDN. Прокси картинок и API данных отдавали ответ через функцию на КАЖДЫЙ запрос
// (в заголовке было только max-age для браузера, а CDN Vercel кэширует функции лишь по s-maxage).
//
// Эти ответы зависят только от файлов данных, которые меняются вместе с деплоем (кэш CDN привязан к деплою),
// поэтому CDN может безопасно отдавать их повторно, не вызывая функцию. НЕ применять к ответам, зависящим от
// пользователя (сессия, избранное, форум, оплата) и к вызовам ИИ.

/** Данные, зависящие только от запроса и файлов деплоя (бренды, модели, поколения, поиск). */
export const CDN_CACHE_DATA = {
  'Cache-Control': 'public, max-age=60, s-maxage=3600, stale-while-revalidate=86400',
} as const

/** Картинки (прокси сторонних изображений): меняются крайне редко. */
export const CDN_CACHE_IMAGE = {
  'Cache-Control': 'public, max-age=604800, s-maxage=2592000, stale-while-revalidate=604800, immutable',
} as const

/** Ошибки и «картинки нет»: запоминаем ненадолго, чтобы повторные запросы не будили функцию каждый раз. */
export const CDN_CACHE_MISS = {
  'Cache-Control': 'public, max-age=60, s-maxage=300',
} as const
